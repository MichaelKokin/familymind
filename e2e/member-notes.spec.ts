import { test, expect } from "@playwright/test";
import { randomUUID } from "node:crypto";
import { readFile } from "node:fs/promises";
import path from "node:path";
import { LocalCaseAccess } from "../src/private-case/access";
import { PrivateCaseStore } from "../src/private-case/server-store";
import { notesText as t } from "../src/i18n/notes";

const origin = "http://127.0.0.1:3001";
const root = process.env.FAMILYMIND_PRIVATE_E2E_ROOT;

test("separate browser member accounts preserve private notes and enforce revocation", async ({ page, browser }) => {
  if (!root || await readFile(path.join(root, ".synthetic-e2e-owned"), "utf8") !== "family-mind-synthetic-e2e\n") throw new Error("Synthetic test root required");
  const store = new PrivateCaseStore(root);
  const value = await store.save({ schemaVersion: 1, id: `synthetic-notes-${randomUUID()}`, title: "SYNTHETIC notes case", revision: 0, updatedAt: new Date().toISOString(), subject: { personId: "synthetic_note_subject", name: "Синтетическая Персона", dateText: "около 1900", livingStatus: "deceased" }, sources: [], known: [], question: "Учебный вопрос", notes: "", aiRuns: [], reviews: [] }, null);
  const { token } = await new LocalCaseAccess(root, origin).createBootstrap(value.id);
  await page.goto(`/case#token=${encodeURIComponent(token)}`);
  await expect(page.getByTestId("private-case")).toBeVisible();
  await page.goto("/case/members");
  await expect(page.getByTestId("member-notes")).toBeVisible();
  await page.getByLabel(t.text, { exact: true }).fill("SYNTHETIC owner personal note");
  await expect(page.getByLabel(t.visibility)).toHaveValue("private");
  await page.getByRole("button", { name: t.submit, exact: true }).click();
  await expect(page.getByText("SYNTHETIC owner personal note", { exact: true })).toBeVisible();
  await page.getByLabel(t.text, { exact: true }).fill("SYNTHETIC owner family note");
  await page.getByLabel(t.visibility).selectOption("family");
  await page.getByRole("button", { name: t.submit, exact: true }).click();
  await expect(page.getByText("SYNTHETIC owner family note", { exact: true })).toBeVisible();
  await page.getByLabel(t.inviteName).fill("Synthetic invited member");
  await page.getByRole("button", { name: t.invite, exact: true }).click();
  const link = page.getByLabel(t.inviteLink, { exact: true });
  await expect(link).toBeVisible();
  const invitation = await link.inputValue();
  const memberContext = await browser.newContext();
  const memberPage = await memberContext.newPage();
  try {
    await memberPage.goto(invitation);
    await expect(memberPage.getByTestId("member-notes")).toBeVisible();
    await expect(memberPage).toHaveURL(`${origin}/case/members`);
    await expect(memberPage.getByText("SYNTHETIC owner personal note", { exact: true })).toHaveCount(0);
    await expect(memberPage.getByText("SYNTHETIC owner family note", { exact: true })).toBeVisible();
    expect((await memberPage.request.get(`${origin}/api/private/case`)).status()).toBe(401);
    await memberPage.getByLabel(t.text, { exact: true }).fill("SYNTHETIC member personal note");
    await memberPage.getByRole("button", { name: t.submit, exact: true }).click();
    await expect(memberPage.getByText("SYNTHETIC member personal note", { exact: true })).toBeVisible();
    await memberPage.reload();
    await expect(memberPage.getByText("SYNTHETIC member personal note", { exact: true })).toBeVisible();
    const memberNotes = await (await memberPage.request.get(`${origin}/api/private/notes`)).json();
    const personal = memberNotes.notes.find((note: { text: string }) => note.text === "SYNTHETIC member personal note");
    expect(Boolean(personal)).toBe(true);
    await page.reload();
    await expect(page.getByTestId("member-notes")).toBeVisible();
    await expect(page.getByText("SYNTHETIC member personal note", { exact: true })).toHaveCount(0);
    expect((await page.request.get(`${origin}/api/private/notes?id=${personal.id}`)).status()).toBe(404);
    const noteCard = memberPage.getByTestId(`note-${personal.id}`);
    await noteCard.getByRole("button", { name: t.edit, exact: true }).click();
    await memberPage.getByLabel(t.visibility).selectOption("family");
    await memberPage.getByRole("button", { name: t.submit, exact: true }).click();
    await expect(noteCard.getByText(t.noteFamily, { exact: true })).toBeVisible();
    await page.getByRole("button", { name: t.retry, exact: true }).click();
    await expect(page.getByText("SYNTHETIC member personal note", { exact: true })).toBeVisible();
    await page.getByRole("button", { name: t.revoke, exact: true }).click();
    await expect(page.getByText(t.revokeDone, { exact: true })).toBeVisible();
    await memberPage.getByRole("button", { name: t.retry, exact: true }).click();
    await expect(memberPage.getByText(t.locked, { exact: true })).toBeVisible();
    await expect(memberPage.getByText("SYNTHETIC member personal note", { exact: true })).toHaveCount(0);
    expect((await memberPage.request.get(`${origin}/api/private/notes?id=${personal.id}`)).status()).toBe(401);
  } finally { await memberContext.close(); }
});
